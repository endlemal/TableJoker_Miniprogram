// 显示用简称：北京市 → 北京；广东省 → 广东；内蒙古自治区 → 内蒙古
// 注意别用 /省|市$/ 这类简单规则，自治区/特别行政区要先去长后缀。
const LONG_SUFFIX = /(特别行政区|壮族自治区|回族自治区|维吾尔自治区|自治区|省|市)$/

export function shortRegion(name) {
  const v = String(name || '')
  return v.replace(LONG_SUFFIX, '') || v
}
