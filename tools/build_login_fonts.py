"""Generate the login ticket's embedded font subsets using only the standard library.

Run from any directory: python3 tools/build_login_fonts.py
Only src/components/login-ticket/fonts.css is written. The Google Fonts CSS API
and fonts.gstatic.com must be reachable; the global font bundle is untouched.
"""

import base64
from pathlib import Path
import re
import urllib.parse
import urllib.request


ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "src/components/login-ticket/fonts.css"
USER_AGENT = (
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36"
)
ASCII = "".join(chr(code) for code in range(0x20, 0x7F))
STATIC_TEXT = (
    "欢迎来到桌趣须知登录中"
    "获取你的微信头像加入时间微信昵称所在城市"
    "聚会、玩桌游，或者参与比赛，点击下方开始吧！"
    "点击获取点击选择点击填写换一张"
)
SANS_TEXT = "".join(sorted(set(ASCII + STATIC_TEXT)))
FACES = (
    ("TicketDisplay", "ZCOOL QingKe HuangYou", 400, ASCII + "欢迎来到"),
    ("TicketEnglish", "Montserrat", 900, ASCII),
    ("TicketSans", "Noto Sans SC", 400, SANS_TEXT),
    ("TicketSans", "Noto Sans SC", 500, SANS_TEXT),
    ("TicketSans", "Noto Sans SC", 900, SANS_TEXT),
)
WOFF2_SOURCE = re.compile(
    r"src:\s*url\([\"']?([^\"')\s]+)[\"']?\)"
    r"\s*format\([\"']woff2[\"']\)"
)


def download(url):
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(request, timeout=30) as response:
        return response.read()


def fetch_font(family, weight, characters):
    query = urllib.parse.urlencode(
        {
            "family": f"{family}:wght@{weight}",
            "text": "".join(sorted(set(characters))),
        }
    )
    css = download("https://fonts.googleapis.com/css2?" + query).decode("utf-8")
    sources = list(dict.fromkeys(WOFF2_SOURCE.findall(css)))
    if len(sources) != 1:
        raise RuntimeError(f"Expected one WOFF2 subset for {family} {weight}")
    source = sources[0]
    parsed = urllib.parse.urlparse(source)
    if parsed.scheme != "https" or parsed.hostname != "fonts.gstatic.com":
        raise RuntimeError(f"Unexpected font source for {family} {weight}")
    data = download(source)
    if data[:4] != b"wOF2":
        raise RuntimeError(f"Invalid WOFF2 response for {family} {weight}")
    return data


def main():
    lines = [
        "/* Generated by tools/build_login_fonts.py; do not edit manually.",
        " * Google Fonts: ZCOOL QingKe HuangYou 400, Montserrat 900,",
        " * Noto Sans SC 400/500/900. All use the SIL Open Font License.",
        " * Ticket-prefixed families are reserved for the login-ticket component.",
        " */",
    ]
    font_bytes = 0
    for alias, family, weight, characters in FACES:
        data = fetch_font(family, weight, characters)
        font_bytes += len(data)
        encoded = base64.b64encode(data).decode("ascii")
        lines.append(
            f'@font-face {{ font-family: "{alias}"; font-style: normal; '
            f'font-weight: {weight}; src: url("data:font/woff2;base64,{encoded}") '
            'format("woff2"); }'
        )
        print(f"{alias} {weight}: {len(set(characters))} characters, {len(data)} bytes")

    # Fetch every face before replacing the bundle, so a failed request leaves it intact.
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    result = "\n".join(lines) + "\n"
    OUTPUT.write_text(result, encoding="utf-8")
    print(f"{len(FACES)} faces; {font_bytes} font bytes; {len(result.encode('utf-8'))} CSS bytes")
    print(OUTPUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
