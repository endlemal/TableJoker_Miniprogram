// 房间集成：预设、OB 权限、主持人定胜与玩家收分。node tools/tally-room-test.mjs
import assert from 'node:assert/strict'
globalThis.uni = {}
const R = await import('../src/common/tally-room.js')
const T = await import('../src/common/tally.js')
const { room, me } = await import('../src/mock/data.js')
R.initTally([...room.seats, ...room.waiting], me.nickname, room.startScore)
const [full, open] = R.tally.tables
assert.deepEqual(R.tally.tables.map(t => t.seats.filter(Boolean).length), [10, 9])
assert.equal(new Set(R.tally.tables.flatMap(t => t.seats.filter(Boolean).map(s => s.pid))).size, 19)
assert.equal(R.tally.members.length, 20)
assert.ok(R.join(full.id))
assert.equal(R.observe(full.id), '')
assert.equal(R.mySpot(), null)
assert.equal(R.viewSpot().i, -1)
assert.equal(R.viewSpot().observing, true)
assert.ok(R.myAct('allin'))
assert.ok(R.myCollect(0))
assert.equal(full.seats.filter(Boolean).length, 10)
console.log('✓ 10 人仅 OB，9 人桌留一席；观战不占座且不能下注、收分')

T.startHand(full, { sb: 100, bb: 200, ante: 0 })
let steps = 0
while (full.hand.street !== 'collect' && steps++ < 60) {
  const i = full.hand.toAct
  T.act(full, i, T.options(full, i).canCheck ? 'check' : 'call')
}
assert.equal(full.hand.street, 'collect')
R.tally.iAmHost = false
R.togglePick(0, full.hand.pots[0].elig[0])
assert.deepEqual({ ...R.tally.picks }, {})
assert.ok(R.confirmDesignation())
R.tally.iAmHost = true
R.runTally(true)
await new Promise(resolve => setTimeout(resolve, 380))
R.runTally(false)
assert.equal(full._hostChoosing, true)
assert.ok(full._deadline - Date.now() > 28000)
full.hand.pots.forEach((p, k) => R.togglePick(k, p.elig[0]))
assert.equal(R.confirmDesignation(), '')
assert.equal(full.hand.street, 'payout')
assert.deepEqual({ ...R.tally.picks }, {})
assert.ok(R.myCollect(0))
T.unpaid(full).forEach(u => T.collect(full, u.k, u.seat))
assert.equal(full.hand.street, 'done')
console.log('✓ OB 主持人拥有完整定胜时限；普通观战者不可定胜，确认后进入独立收分阶段')

assert.equal(R.join(open.id), '')
assert.equal(R.tally.observing, '')
assert.equal(R.mySpot().t.id, open.id)
assert.equal(open.seats.filter(Boolean).length, 10)
assert.ok(R.observe(full.id))
T.startHand(open, { sb: 100, bb: 200, ante: 0 })
while (open.hand.street !== 'collect') {
  const i = open.hand.toAct
  T.act(open, i, T.options(open, i).canCheck ? 'check' : 'call')
}
const mine = R.mySpot().i
R.togglePick(0, mine)
assert.equal(R.confirmDesignation(), '')
const before = open.seats[mine].stack
assert.equal(R.myCollect(0), '')
assert.ok(open.seats[mine].stack > before)
assert.equal(open.hand.street, 'done')
R.leaveTable()
assert.equal(R.observe(full.id), '')
R.removeTable(full.id)
assert.equal(R.viewSpot(), null)
assert.equal(R.tally.observing, '')
console.log('✓ OB 转入座清除观战状态；玩家可收自己的分，删桌清理观战引用')

// 无分只在结算后移至 OB；投入全下的 0 余额与真正淘汰必须分开处理。
const shortTable = R.createTable(3)
R.setAssets(R.tally.me, 1000)
assert.equal(R.join(shortTable.id), '')
const selfSeat = R.mySpot().i
const opponent = R.tally.members.find(m => m.name !== R.tally.me)
const empty = R.tally.members.find(m => m.name !== R.tally.me && m.name !== opponent.name)
T.sit(shortTable, 1, { ...opponent, pid: opponent.name, stack: 1000, bot: true })
T.sit(shortTable, 2, { ...empty, pid: empty.name, stack: 0, bot: true })
R.moveBustedToOb(shortTable)
assert.equal(shortTable.seats[2], null)
assert.equal(shortTable.observers[0].pid, empty.name)
assert.equal(R.tally.assets[empty.name], 0)
T.startHand(shortTable, { sb: 100, bb: 200, ante: 0 })
assert.equal(R.myAct('allin'), '')
R.moveBustedToOb(shortTable)
assert.equal(R.mySpot().i, selfSeat)
assert.equal(shortTable.seats[selfSeat].stack, 0)
assert.ok(T.act(shortTable, 1, 'call').ok)
assert.equal(shortTable.hand.street, 'collect')
R.moveBustedToOb(shortTable)
assert.equal(shortTable.seats.filter(Boolean).length, 2)
assert.ok(T.designate(shortTable, [[1]]).ok)
R.moveBustedToOb(shortTable)
assert.equal(shortTable.seats.filter(Boolean).length, 2)
assert.ok(T.collect(shortTable, 0, 1).ok)
R.runTally(true)
await new Promise(resolve => setTimeout(resolve, 380))
R.runTally(false)
assert.equal(shortTable.hand.street, 'done')
assert.equal(shortTable.seats[selfSeat], null)
assert.equal(shortTable.seats[1].stack, 2000)
assert.equal(shortTable.hand.seatRef[selfSeat].pid, R.tally.me)
assert.equal(shortTable.hand.result.delta[selfSeat], -1000)
assert.equal(R.mySpot(), null)
assert.equal(R.viewSpot().t.id, shortTable.id)
assert.equal(R.viewSpot().observing, true)
assert.equal(R.tally.assets[R.tally.me], 0)
assert.equal(shortTable.observers.filter(s => s.pid === R.tally.me).length, 1)
R.moveBustedToOb(shortTable)
assert.equal(shortTable.observers.filter(s => s.pid === R.tally.me).length, 1)
assert.ok(R.join(shortTable.id))
R.setAssets(R.tally.me, 500)
assert.equal(R.join(shortTable.id), '')
assert.equal(shortTable.observers.some(s => s.pid === R.tally.me), false)
assert.equal(R.tally.observing, '')
assert.equal(R.mySpot().t.id, shortTable.id)
R.leaveTable()
shortTable.hand = null
assert.equal(R.join(shortTable.id), '')
R.setAssets(R.tally.me, 0)
assert.equal(R.mySpot(), null)
assert.equal(R.viewSpot().observing, true)
console.log('✓ 无分转 OB 并释放席位；All-in 与待收分不误移，保留结算记录，补分后可重新入座')

// 原满员桌释放座位后可入座；中途入座只能从下一手参与。
R.leaveObservation()
R.setAssets(R.tally.me, 1000)
const freed = R.createTable(2)
T.sit(freed, 0, { ...opponent, pid: opponent.name, stack: 1000 })
T.sit(freed, 1, { ...empty, pid: empty.name, stack: 1000 })
assert.ok(R.join(freed.id))
T.startHand(freed, { sb: 100, bb: 200, ante: 0 })
T.forfeit(freed, 1)
freed.seats[1] = null
assert.equal(R.observe(freed.id), '')
assert.equal(R.join(freed.id), '')
assert.equal(R.mySpot().i, 1)
assert.equal(R.tally.observing, '')
assert.notEqual(freed.hand.seatRef[1].pid, R.tally.me)
assert.ok(R.myAct('allin'))
console.log('✓ 满桌空出席位后开放入座，观战可直接入座，中途加入不参与旧手')
